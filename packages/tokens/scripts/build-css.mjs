// Generates two files from src/index.ts (Node ≥ 22.18 — type stripping, no build step):
//   tokens.css  — a Tailwind 4 @theme block for the web portal
//   tokens.json — every token as plain JSON, for places that can't import TypeScript
//                 (apps/mobile/app.config.ts)
// Run: pnpm --filter @skillproof/tokens build   — CI fails if the committed files are stale.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as tokens from "../src/index.ts";

const { colors, fontStack, gap, portalRadius, radius, space, type } = tokens; // motion & co. go to tokens.json only
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lines = [];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

// colors.text.primary → --color-text-primary ; colors.status.verified.fg → --color-status-verified-fg
function walk(obj, path) {
  for (const [key, value] of Object.entries(obj)) {
    const next = [...path, kebab(key)];
    if (typeof value === "object") walk(value, next);
    else lines.push(`  --color-${next.join("-")}: ${value};`);
  }
}
walk(colors, []);

for (const [k, v] of Object.entries(radius)) lines.push(`  --radius-${k}: ${v}px;`);
lines.push(`  --radius-portal: ${portalRadius}px;`);
for (const [k, v] of Object.entries(fontStack)) lines.push(`  --font-${kebab(k)}: ${v};`);
for (const [k, v] of Object.entries(type)) {
  lines.push(`  --text-${kebab(k)}: ${v.size}px;`);
  lines.push(`  --text-${kebab(k)}--line-height: ${v.lineHeight}px;`);
  lines.push(`  --text-${kebab(k)}--letter-spacing: ${v.letterSpacing}px;`);
  lines.push(`  --text-${kebab(k)}--font-weight: ${v.weight};`);
}

// Spacing goes outside @theme, as --space-*: Tailwind reads every --spacing-* as a size for its
// width utilities too, so --spacing-sm (8px) turned max-w-sm into 8px on the portal (28 Oct).
const space_ = [
  ...Object.entries(space).map(([k, v]) => `  --space-${k}: ${v}px;`),
  ...Object.entries(gap).map(([k, v]) => `  --space-gap-${k}: ${v}px;`),
];

const header = "Generated by scripts/build-css.mjs — edit src/index.ts, then `pnpm --filter @skillproof/tokens build`.";
writeFileSync(
  join(root, "tokens.css"),
  `/* ${header} */\n@theme {\n${lines.join("\n")}\n}\n\n:root {\n${space_.join("\n")}\n}\n`,
);
writeFileSync(join(root, "tokens.json"), `${JSON.stringify({ $comment: header, ...tokens }, null, 2)}\n`);
console.log(`wrote tokens.css (${lines.length} vars) and tokens.json`);
