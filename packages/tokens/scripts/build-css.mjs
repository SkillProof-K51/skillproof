// Generates tokens.css (a Tailwind 4 @theme block) from src/index.ts.
// Run: pnpm --filter @skillproof/tokens build   (Node ≥ 22.18 — type stripping, no build step)
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { colors, fontStack, radius, space, type } from "../src/index.ts";

const lines = [];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

// colors.text.primary → --color-text-primary ; colors.status.verified.fg → --color-status-verified-fg
function walk(obj, path) {
  for (const [key, value] of Object.entries(obj)) {
    const next = [...path, kebab(key)];
    if (typeof value === "object") walk(value, next);
    else lines.push(`  --color-${next.join("-")}: ${value};`);
  }
}
walk(colors, []);

for (const [k, v] of Object.entries(space)) lines.push(`  --spacing-${k}: ${v}px;`);
for (const [k, v] of Object.entries(radius)) lines.push(`  --radius-${k}: ${v}px;`);
lines.push(`  --font-sans: ${fontStack.sans};`);
lines.push(`  --font-mono: ${fontStack.mono};`);
for (const [k, v] of Object.entries(type)) {
  lines.push(`  --text-${kebab(k)}: ${v.size}px;`);
  lines.push(`  --text-${kebab(k)}--line-height: ${v.lineHeight}px;`);
  lines.push(`  --text-${kebab(k)}--letter-spacing: ${v.letterSpacing}px;`);
  lines.push(`  --text-${kebab(k)}--font-weight: ${v.weight};`);
}

const css = `/* Generated by scripts/build-css.mjs — edit src/index.ts, then \`pnpm --filter @skillproof/tokens build\`. */\n@theme {\n${lines.join("\n")}\n}\n`;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "tokens.css");
writeFileSync(out, css);
console.log(`wrote ${out} (${lines.length} tokens)`);
